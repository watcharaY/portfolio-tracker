// Command xlsx2sql turns the Portfolio-Tracker workbook into a one-shot SQL seed
// for a freshly migrated database:
//
//	go run ./cmd/xlsx2sql -in Portfolio-Tracker.xlsx -out ../private/seed-data.sql
//	psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f ../private/seed-data.sql
//
// The output holds personal financial data. Keep it under private/, which git ignores.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"math"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

// conv turns one cached cell value into a SQL literal.
type conv func(c cell) (string, error)

type column struct {
	name string // target column
	col  string // spreadsheet column letter; "" for a constant
	conv conv
}

// section is one rectangular range of a sheet that feeds one table.
type section struct {
	table       string
	sheet       string
	first, last int    // data rows, inclusive
	key         string // rows whose key cell is empty are skipped
	cols        []column
}

// Ranges follow docs/02-db-er.md "Excel → DB mapping". Order matters: parents
// (brokers, insurers) precede the rows that look them up by name.
var sections = []section{
	{table: "brokers", sheet: "Brokerage", first: 6, last: 15, key: "A", cols: []column{
		{"name", "A", text}, {"current_value", "B", money},
	}},
	{table: "broker_transactions", sheet: "Brokerage", first: 6, last: 305, key: "J", cols: []column{
		{"txn_date", "I", date}, {"broker_id", "J", lookup("brokers", "name")},
		{"type", "K", txnType}, {"amount", "L", money}, {"note", "M", text},
	}},
	{table: "funds", sheet: "Funds", first: 6, last: 105, key: "A", cols: []column{
		{"name", "A", text}, {"category", "B", text}, {"cost", "C", money},
		{"market_value", "D", money}, {"note", "G", text},
	}},
	{table: "pvd_years", sheet: "PVD", first: 6, last: 45, key: "A", cols: []column{
		{"year", "A", integer}, {"self_contribution", "B", money}, {"company_contribution", "C", money},
		{"self_profit", "D", money}, {"company_profit", "E", money}, {"fund_allocation", "J", text},
	}},
	{table: "savings_accounts", sheet: "Savings", first: 6, last: 55, key: "A", cols: []column{
		{"bank", "A", text}, {"balance", "B", money}, {"interest_bp", "C", basisPoints}, {"note", "E", text},
	}},
	{table: "insurers", sheet: "Insurance", first: 6, last: 20, key: "A", cols: []column{
		{"company", "A", text}, {"note", "D", text},
	}},
	{table: "insurance_payments", sheet: "Insurance", first: 6, last: 405, key: "F", cols: []column{
		{"insurer_id", "F", lookup("insurers", "company")}, {"year", "H", nullableInteger},
		{"premium", "I", money}, {"note", "J", text},
	}},
	{table: "salary_months", sheet: "Salary & Tax 2026", first: 5, last: 16, key: "A", cols: []column{
		{"year", "", constant("2026")}, {"month", "A", month}, {"salary", "B", money}, {"bonus", "C", money},
		{"withholding_tax", "D", money}, {"pvd", "E", money}, {"sso", "F", money},
	}},
	{table: "tax_deductions", sheet: "Salary & Tax 2026", first: 5, last: 16, key: "M", cols: []column{
		{"year", "", constant("2026")}, {"item", "M", text}, {"amount", "N", money},
	}},
}

// seededTables are the tables the guard checks. users and sessions are absent
// on purpose: the server seeds its own admin user.
var seededTables = []string{
	"brokers", "broker_transactions", "funds", "pvd_years", "savings_accounts",
	"insurers", "insurance_payments", "salary_months", "tax_deductions",
}

type tableRows struct {
	section *section
	rows    [][]string // SQL literals, one per column
}

func (s *section) extract(sh sheet) (tableRows, error) {
	out := tableRows{section: s}
	for r := s.first; r <= s.last; r++ {
		if sh[s.key+strconv.Itoa(r)].empty() {
			continue
		}
		row := make([]string, len(s.cols))
		for i, c := range s.cols {
			ref := c.col + strconv.Itoa(r)
			v, err := c.conv(sh[ref])
			if err != nil {
				return out, fmt.Errorf("%s!%s (%s.%s): %w", s.sheet, ref, s.table, c.name, err)
			}
			row[i] = v
		}
		out.rows = append(out.rows, row)
	}
	return out, nil
}

func convert(r io.ReaderAt, size int64) (string, []tableRows, error) {
	wb, err := openWorkbook(r, size)
	if err != nil {
		return "", nil, err
	}
	sheets := map[string]sheet{}
	var tables []tableRows
	for i := range sections {
		s := &sections[i]
		sh, ok := sheets[s.sheet]
		if !ok {
			if sh, err = wb.sheet(s.sheet); err != nil {
				return "", nil, err
			}
			sheets[s.sheet] = sh
		}
		t, err := s.extract(sh)
		if err != nil {
			return "", nil, err
		}
		tables = append(tables, t)
	}
	return render(tables), tables, nil
}

func render(tables []tableRows) string {
	var b strings.Builder
	b.WriteString("-- Generated by cmd/xlsx2sql. Contains personal financial data: do not commit.\n")
	b.WriteString("BEGIN;\n\nDO $$\nBEGIN\n  IF ")
	for i, t := range seededTables {
		if i > 0 {
			b.WriteString("\n     OR ")
		}
		fmt.Fprintf(&b, "EXISTS (SELECT 1 FROM %s)", t)
	}
	b.WriteString(" THEN\n    RAISE EXCEPTION 'seed aborted: portfolio tables already contain data';\n  END IF;\nEND $$;\n")
	for _, t := range tables {
		if len(t.rows) == 0 {
			continue
		}
		names := make([]string, len(t.section.cols))
		for i, c := range t.section.cols {
			names[i] = c.name
		}
		fmt.Fprintf(&b, "\nINSERT INTO %s (%s) VALUES\n", t.section.table, strings.Join(names, ", "))
		for i, row := range t.rows {
			sep := ","
			if i == len(t.rows)-1 {
				sep = ";"
			}
			fmt.Fprintf(&b, "  (%s)%s\n", strings.Join(row, ", "), sep)
		}
	}
	b.WriteString("\nCOMMIT;\n")
	return b.String()
}

func quote(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func number(c cell) (float64, error) {
	f, err := strconv.ParseFloat(strings.TrimSpace(c.text), 64)
	if err != nil {
		return 0, fmt.Errorf("want a number, got %q", c.text)
	}
	return f, nil
}

func text(c cell) (string, error) { return quote(strings.TrimSpace(c.text)), nil }

// money converts THB to satang. An empty cell is 0.
func money(c cell) (string, error) {
	if c.empty() {
		return "0", nil
	}
	f, err := number(c)
	return strconv.FormatInt(int64(math.Round(f*100)), 10), err
}

// basisPoints converts a fraction such as 0.025 to 250. An empty cell is 0.
func basisPoints(c cell) (string, error) {
	if c.empty() {
		return "0", nil
	}
	f, err := number(c)
	return strconv.FormatInt(int64(math.Round(f*10_000)), 10), err
}

func integer(c cell) (string, error) {
	f, err := number(c)
	if err == nil && f != math.Trunc(f) {
		err = fmt.Errorf("want a whole number, got %q", c.text)
	}
	return strconv.FormatInt(int64(f), 10), err
}

func nullableInteger(c cell) (string, error) {
	if c.empty() {
		return "NULL", nil
	}
	return integer(c)
}

// date converts an Excel 1900-system serial to an ISO date. Serial 60 is the
// fictitious 1900-02-29 that Excel keeps for Lotus compatibility, so serials
// above it count from 1899-12-30 and serials below it from 1899-12-31.
func date(c cell) (string, error) {
	if c.empty() {
		return "NULL", nil
	}
	f, err := number(c)
	if err != nil {
		return "", err
	}
	serial := int(math.Floor(f))
	base := time.Date(1899, 12, 30, 0, 0, 0, 0, time.UTC)
	switch {
	case serial < 1 || serial == 60:
		return "", fmt.Errorf("serial %d is not a real date", serial)
	case serial < 60:
		base = base.AddDate(0, 0, 1)
	}
	return quote(base.AddDate(0, 0, serial).Format(time.DateOnly)), nil
}

func txnType(c cell) (string, error) {
	switch strings.ToLower(strings.TrimSpace(c.text)) {
	case "deposit":
		return "'deposit'", nil
	case "withdraw":
		return "'withdraw'", nil
	}
	return "", fmt.Errorf("want Deposit or Withdraw, got %q", c.text)
}

var months = map[string]int{
	"jan": 1, "feb": 2, "mar": 3, "apr": 4, "may": 5, "jun": 6,
	"jul": 7, "aug": 8, "sep": 9, "oct": 10, "nov": 11, "dec": 12,
}

func month(c cell) (string, error) {
	m, ok := months[strings.ToLower(strings.TrimSpace(c.text))]
	if !ok {
		return "", fmt.Errorf("want a month name Jan..Dec, got %q", c.text)
	}
	return strconv.Itoa(m), nil
}

// lookup resolves a name to its parent row id. An unknown name yields NULL,
// which the NOT NULL foreign key rejects, so the whole seed rolls back.
func lookup(table, nameCol string) conv {
	return func(c cell) (string, error) {
		return fmt.Sprintf("(SELECT id FROM %s WHERE %s = %s)", table, nameCol, quote(strings.TrimSpace(c.text))), nil
	}
}

func constant(v string) conv { return func(cell) (string, error) { return v, nil } }

func main() {
	in := flag.String("in", "", "path to Portfolio-Tracker.xlsx (required)")
	out := flag.String("out", filepath.Join("..", "private", "seed-data.sql"), "SQL file to write")
	flag.Parse()
	if *in == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "xlsx2sql:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	data, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	sql, tables, err := convert(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o700); err != nil {
		return err
	}
	if err := os.WriteFile(out, []byte(sql), 0o600); err != nil {
		return err
	}
	for _, t := range tables {
		fmt.Fprintf(os.Stderr, "%-20s %d rows\n", t.section.table, len(t.rows))
	}
	fmt.Fprintln(os.Stderr, "wrote", out)
	return nil
}
